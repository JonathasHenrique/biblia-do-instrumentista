// Construtor dinâmico de partitura para qualquer hino
export function buildScoreABC(hymnNumber, title, targetTone = "C", meter = "4/4") {
  const specific = HYMN_SCORES[hymnNumber];
  if (specific) {
    return `X: 1
T: Hino ${hymnNumber} - ${specific.title}
C: Harpa Cristã (Padrão Assembleia de Deus)
M: ${specific.meter}
L: ${specific.unit}
K: ${targetTone}
%%scale 0.95
%%staffsep 45
V: 1 clef=treble name="Violão / Melodia" snm="Vl"
V: 2 clef=bass name="Contrabaixo" snm="Bx"
${specific.abcBody}`;
  }

  // Partitura base de acompanhamento para os demais hinos
  return `X: 1
T: Hino ${hymnNumber} - ${title}
C: Harpa Cristã (Padrão Assembleia de Deus)
M: ${meter}
L: 1/4
K: ${targetTone}
%%scale 0.95
%%staffsep 45
V: 1 clef=treble name="Violão / Harmonia" snm="Vl"
V: 2 clef=bass name="Contrabaixo" snm="Bx"
[V:1] "${targetTone}" [CEG]2 [CEG]2 | "${targetTone}" [CEG]2 [CEG]2 | "G" [B,DF]2 [B,DF]2 | "${targetTone}" [CEG]4 |
[V:2] [K:${targetTone}] C,,2 G,,2 | C,,2 G,,2 | D,,2 G,,2 | C,,4 |
[V:1] "F" [CFA]2 [CFA]2 | "${targetTone}" [CEG]2 [CEG]2 | "G" [B,DF]2 [B,DF]2 | "${targetTone}" [CEG]4 |]
[V:2] F,,2 C,,2 | C,,2 G,,2 | D,,2 G,,2 | C,,4 |]`;
}
